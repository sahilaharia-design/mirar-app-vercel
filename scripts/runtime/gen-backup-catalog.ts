// Generates docs/proposed/option-b/002_catalog_seed.sql from the frozen catalog. Run: npx tsx scripts/runtime/gen-backup-catalog.ts
// backup-sql.test.ts / backup.test.ts fail if the checked-in file differs from a fresh generation (catalog drift guard).
import { writeFileSync } from 'fs';
import { ENGINE_VERSION } from '../../lib/innerRep/v2/config';
import { buildVocabulary } from '../../lib/innerRep/backup/events';

export function catalogSeedSql(): string {
  const v = buildVocabulary(ENGINE_VERSION);
  const rows = [...v.templates.map((id) => ['template', id]), ...v.options.map((id) => ['option', id]), ...v.steps.map((id) => ['step', id])];
  return `-- GENERATED by scripts/runtime/gen-backup-catalog.ts from the frozen catalog. DO NOT EDIT BY HAND. DRAFT: NOT APPLIED.\n-- Public reference data only (ids the engine can emit). Contains nothing personal.\ninsert into public.inner_rep_catalog_vocab (engine_version, kind, id) values\n${rows.map(([k, id]) => `  ('${v.engine}', '${k}', '${id}')`).join(',\n')}\non conflict do nothing;\n`;
}
if (require.main === module) { writeFileSync(__dirname + '/../../docs/proposed/option-b/002_catalog_seed.sql', catalogSeedSql()); console.log('written'); }
