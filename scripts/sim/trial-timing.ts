// READ-ONLY / LOCAL: compares server-authoritative trial-timing rules for a 14-day trial that starts at the first completed rep.
//   A  local-calendar-day: ends at the end of local day 14 (start zone) + 12 h courtesy
//   B  336 hours from the server-recorded start
//   B+ 336 hours + a fixed 12 h courtesy (no time zone needed)
//   C  local-calendar-day with no courtesy
// A habitual practitioner opens the app once per local calendar date at the first opportunity at or after their habit hour; the real runtime
// allows one rep per device-local date (scripts/sim/trial-boundaries.ts). We count how many daily reps each rule lets them complete.
// Nothing here touches the engine, the app, Supabase or any deployment. Run: npx tsx scripts/sim/trial-timing.ts  (writes docs/sim/trial-timing.md)
import { writeFileSync } from 'fs';

const H = 3600000, DAY = 24 * H, N = 14;
type Rule = { id: string; label: string; end: (t0: number, z0: number) => number };
const dayIdx = (t: number, z: number) => Math.floor((t + z * 60000) / DAY);
const midnightOf = (idx: number, z: number) => idx * DAY - z * 60000;
export const RULES: Rule[] = [
  { id: 'A', label: 'local calendar day 14, plus 12 h', end: (t0, z0) => midnightOf(dayIdx(t0, z0) + N, z0) + 12 * H },
  { id: 'B', label: '336 hours exactly', end: (t0) => t0 + N * DAY },
  { id: 'B+', label: '336 hours plus 12 h', end: (t0) => t0 + N * DAY + 12 * H },
  { id: 'C', label: 'local calendar day 14, no courtesy', end: (t0, z0) => midnightOf(dayIdx(t0, z0) + N, z0) },
];

const IST = 330;
const T_BASE = Date.UTC(2026, 9, 14, 18, 30); // 2026-10-15 00:00 IST
interface Scenario { id: string; zone: (t: number, t0: number) => number }
const stay = (z: number) => (t: number) => z;
const moveAt = (afterDays: number, to: number) => (t: number, t0: number) => (t >= t0 + afterDays * DAY ? to : IST);
const SCEN: Scenario[] = [
  { id: 'no travel (IST)', zone: stay(IST) },
  { id: 'IST→Dubai (-1.5 h) day 6', zone: moveAt(6, 240) },
  { id: 'IST→London (-4.5 h) day 6', zone: moveAt(6, 60) },
  { id: 'IST→US west (-13.5 h) day 3', zone: moveAt(3, -480) },
  { id: 'IST→US west (-13.5 h) day 6', zone: moveAt(6, -480) },
  { id: 'IST→US west (-13.5 h) day 10', zone: moveAt(10, -480) },
  { id: 'IST→Japan (+3.5 h) day 6', zone: moveAt(6, 540) },
];

/** Daily reps completed before the rule's end by someone who practises once per device-local date at/after habit hour h. */
function reps(rule: Rule, startHour: number, habitHour: number, sc: Scenario) {
  const t0 = T_BASE + startHour * H, end = rule.end(t0, IST);
  const done = new Set<number>([dayIdx(t0, IST)]); let n = 1, denied = 0;
  for (let t = t0 + 15 * 60000; t < t0 + 19 * DAY; t += 15 * 60000) {
    const z = sc.zone(t, t0), d = dayIdx(t, z), hr = (((t + z * 60000) % DAY) + DAY) % DAY / H;
    if (hr >= habitHour && !done.has(d)) { done.add(d); if (t < end) n++; else denied++; }
  }
  return { n, denied };
}

const out: string[] = [];
const P = (s = '') => out.push(s);
P('# Trial timing rules compared (generated, local)');
P();
P('Generated by `scripts/sim/trial-timing.ts`. Habitual practitioner model: one rep per device-local calendar date at the first opportunity at or after their habit hour; the real runtime enforces one rep per local date. 24 start hours x 24 habit hours x 7 travel scenarios = 4,032 cases per rule. **14 reps** is the fair baseline (one for each of 14 calendar dates starting with the day of the first rep). Fewer than 14 means a day was lost to the rule; more than 14 is a bonus day.');
P();
P('| Rule | Cases | Mean reps | Min | Max | Exactly 14 | 15 (bonus day) | Fewer than 14 (day lost) |');
P('|---|---|---|---|---|---|---|---|');
const tally: Record<string, { all: number[]; byScen: Record<string, number[]> }> = {};
for (const r of RULES) {
  const all: number[] = []; const byScen: Record<string, number[]> = {};
  for (const sc of SCEN) { byScen[sc.id] = []; for (let s = 0; s < 24; s++) for (let h = 0; h < 24; h++) { const v = reps(r, s, h, sc).n; all.push(v); byScen[sc.id].push(v); } }
  tally[r.id] = { all, byScen };
  const c = (f: (v: number) => boolean) => `${((100 * all.filter(f).length) / all.length).toFixed(1)}%`;
  P(`| ${r.id}: ${r.label} | ${all.length} | ${(all.reduce((a, b) => a + b, 0) / all.length).toFixed(2)} | ${Math.min(...all)} | ${Math.max(...all)} | ${c((v) => v === 14)} | ${c((v) => v === 15)} | ${c((v) => v < 14)} |`);
}
P();
P('### Share of cases in which a day is lost (fewer than 14 reps), by travel scenario');
P();
P(`| Scenario | ${RULES.map((r) => r.id).join(' | ')} |`);
P(`|---|${RULES.map(() => '---').join('|')}|`);
for (const sc of SCEN) P(`| ${sc.id} | ${RULES.map((r) => `${((100 * tally[r.id].byScen[sc.id].filter((v) => v < 14).length) / 576).toFixed(1)}%`).join(' | ')} |`);
P();
P('### No travel: reps by habit hour for someone who starts at 22:00 and someone who starts at 07:00 (the extreme start hours)');
P();
P('| Rule | start 22:00, habit 07:00 | start 22:00, habit 22:00 | start 07:00, habit 07:00 | start 07:00, habit 21:00 |');
P('|---|---|---|---|---|');
for (const r of RULES) P(`| ${r.id} | ${reps(r, 22, 7, SCEN[0]).n} | ${reps(r, 22, 22, SCEN[0]).n} | ${reps(r, 7, 7, SCEN[0]).n} | ${reps(r, 7, 21, SCEN[0]).n} |`);
P();


P('### Courtesy sweep for the 336-hour rule (same 4,032 cases)');
P();
P('| Courtesy added to 336 h | Mean reps | Day lost (<14) | Exactly 14 | 15 | 16 |');
P('|---|---|---|---|---|---|');
for (const c of [0, 3, 6, 9, 12, 15, 24]) {
  const r: Rule = { id: 'x', label: 'x', end: (t0) => t0 + N * DAY + c * H }; const all: number[] = [];
  for (const sc of SCEN) for (let s = 0; s < 24; s++) for (let h = 0; h < 24; h++) all.push(reps(r, s, h, sc).n);
  const pc = (f: (v: number) => boolean) => `${((100 * all.filter(f).length) / all.length).toFixed(1)}%`;
  P(`| +${c} h | ${(all.reduce((a, b) => a + b, 0) / all.length).toFixed(2)} | ${pc((v) => v < 14)} | ${pc((v) => v === 14)} | ${pc((v) => v === 15)} | ${pc((v) => v === 16)} |`);
}
P();
// Contract test vectors for the recommended rule(s)
const fmt = (t: number, z = IST) => { const d = new Date(t + z * 60000); return `${d.toISOString().slice(0, 16).replace('T', ' ')} (UTC${z >= 0 ? '+' : '-'}${Math.floor(Math.abs(z) / 60)}:${String(Math.abs(z) % 60).padStart(2, '0')})`; };
P('### Test vectors (start instant in India time; ends are absolute instants, shown in India time)');
P();
P('| First completed rep | A ends | B ends | B+ ends (B+ day-7 note / day-12 note) |');
P('|---|---|---|---|');
for (const [label, ms] of [['2026-10-15 07:10', T_BASE + 7 * H + 10 * 60000], ['2026-10-15 23:50', T_BASE + 23 * H + 50 * 60000], ['2026-10-16 00:05', T_BASE + 24 * H + 5 * 60000]] as [string, number][])
  P(`| ${label} IST | ${fmt(RULES[0].end(ms, IST))} | ${fmt(RULES[1].end(ms, IST))} | ${fmt(RULES[2].end(ms, IST))} (${fmt(ms + 7 * DAY)} / ${fmt(ms + 12 * DAY)}) |`);
writeFileSync('docs/sim/trial-timing.md', out.join('\n') + '\n');
console.log(out.join('\n'));
